    /**
     * Infer the growing season for any crop from the mappings.
     */
    private function inferCropSeason(string $normalizedName): string
    {
        $mappings = $this->getSeasonMappings();

        foreach ($mappings as $season => $crops) {
            if (in_array($normalizedName, $crops, true)) {
                return $season;
            }
        }

        // Fallback heuristic: check if the DB record has a season column
        $dbCrop = \DB::table('crops')
            ->whereRaw('LOWER(name) = ?', [$normalizedName])
            ->first();

        if ($dbCrop && ! empty($dbCrop->season)) {
            $dbSeason = strtolower(trim($dbCrop->season));
            if (str_contains($dbSeason, 'rabi')) {
                return 'rabi';
            }
            if (str_contains($dbSeason, 'zaid') || str_contains($dbSeason, 'summer')) {
                return 'zaid';
            }
            if (str_contains($dbSeason, 'perennial') || str_contains($dbSeason, 'annual')) {
                return 'perennial';
            }
        }

        return 'kharif';
    }

